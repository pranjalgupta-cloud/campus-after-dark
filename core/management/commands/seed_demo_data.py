    # ─────────────────────────────────────────────────────────────────────
    def _seed_platform_settings(self):
        from bookings.models import PlatformSetting
        _, created = PlatformSetting.objects.get_or_create(
            key='commission_rate',
            defaults={'value': '10', 'description': 'Platform commission percentage charged on each booking'}
        )
        if created:
            self.stdout.write('  [+] Platform commission rate set to 10%')

    def _seed_amenities(self):
        from facilities.models import Amenity
        amenities = [
            ('Wi-Fi', 'bi-wifi'), ('Air Conditioning', 'bi-thermometer-snow'),
            ('Projector', 'bi-projector'), ('Whiteboard', 'bi-easel'),
            ('Sound System', 'bi-speaker'), ('Parking', 'bi-car-front'),
            ('Washrooms', 'bi-door-open'), ('CCTV Security', 'bi-camera-video'),
            ('Generator Backup', 'bi-lightning-charge'), ('Cafeteria Nearby', 'bi-cup-hot'),
            ('Disabled Access', 'bi-universal-access'), ('Stage', 'bi-star'),
            ('Computers', 'bi-pc-display'), ('High-Speed Internet', 'bi-router'),
            ('Natural Lighting', 'bi-sun'), ('Floodlights', 'bi-lightbulb'),
        ]
        count = 0
        for name, icon in amenities:
            _, created = Amenity.objects.get_or_create(name=name, defaults={'icon': icon})
            if created:
                count += 1
        self.stdout.write(f'  [+] {count} amenities created')

    def _seed_admin(self):
        from accounts.models import User
        admin, created = User.objects.get_or_create(
            email='admin@campusafterdark.in',
            defaults={
                'username': 'admin@campusafterdark.in',
                'first_name': 'Platform', 'last_name': 'Admin',
                'role': User.ROLE_ADMIN,
                'is_staff': True, 'is_superuser': True,
                'account_status': User.STATUS_ACTIVE,
            }
        )
        if created:
            admin.set_password('Admin@1234')
            admin.save()
            self.stdout.write('  [+] Admin account created')
        return admin

