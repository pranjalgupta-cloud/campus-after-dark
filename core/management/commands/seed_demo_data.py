    # ─────────────────────────────────────────────────────────────────────
    def _seed_bookings(self, institutions, orgs):
        from facilities.models import Facility
        from bookings.models import Booking, BookingStatusHistory, Payment, Payout, PlatformSetting
        if not institutions or not orgs:
            return

        facilities = list(Facility.objects.filter(institution__in=institutions, status='published'))
        if not facilities or not orgs:
            return

        today = timezone.now().date()
        commission_rate = PlatformSetting.get_commission_rate()

        bookings_data = [
            {
                'facility': facilities[0],
                'organization': orgs[0],
                'booked_date': today + datetime.timedelta(days=10),
                'start_time': datetime.time(10, 0),
                'end_time': datetime.time(16, 0),
                'attendee_count': 300,
                'purpose': '[DEMO] Annual Corporate Conference 2025',
                'status': 'confirmed',
            },
            {
                'facility': facilities[1],
                'organization': orgs[2],
                'booked_date': today + datetime.timedelta(days=5),
                'start_time': datetime.time(9, 0),
                'end_time': datetime.time(13, 0),
                'attendee_count': 50,
                'purpose': '[DEMO] Python Programming Workshop',
                'status': 'pending',
            },
            {
                'facility': facilities[2] if len(facilities) > 2 else facilities[0],
                'organization': orgs[1] if len(orgs) > 1 else orgs[0],
                'booked_date': today - datetime.timedelta(days=15),
                'start_time': datetime.time(10, 0),
                'end_time': datetime.time(18, 0),
                'attendee_count': 100,
                'purpose': '[DEMO] Sports Leadership Summit',
                'status': 'completed',
            },
            {
                'facility': facilities[0],
                'organization': orgs[0],
                'booked_date': today + datetime.timedelta(days=20),
                'start_time': datetime.time(14, 0),
                'end_time': datetime.time(20, 0),
                'attendee_count': 400,
                'purpose': '[DEMO] Product Launch Event',
                'status': 'approved_awaiting_payment',
            },
        ]

        count = 0
        for data in bookings_data:
            facility = data['facility']
            import datetime as dt
            start = dt.datetime.combine(data['booked_date'], data['start_time'])
            end = dt.datetime.combine(data['booked_date'], data['end_time'])
            hours = Decimal(str((end - start).total_seconds() / 3600))
            price_per_hour = facility.price_per_unit
            subtotal = (price_per_hour * hours).quantize(Decimal('0.01'))
            comm_amount = (subtotal * commission_rate / 100).quantize(Decimal('0.01'))
            payout = subtotal - comm_amount

            exists = Booking.objects.filter(
                facility=facility,
                booked_date=data['booked_date'],
                organization=data['organization']
            ).exists()
            if not exists:
                booking = Booking.objects.create(
                    facility=facility,
                    organization=data['organization'],
                    booked_date=data['booked_date'],
                    start_time=data['start_time'],
                    end_time=data['end_time'],
                    attendee_count=data['attendee_count'],
                    purpose=data['purpose'],
                    hours_booked=hours,
                    price_per_hour=price_per_hour,
                    subtotal=subtotal,
                    commission_rate=commission_rate,
                    commission_amount=comm_amount,
                    institution_payout=payout,
                    total_amount=subtotal,
                    status=data['status'],
                )
                BookingStatusHistory.objects.create(
                    booking=booking,
                    from_status='',
                    to_status=data['status'],
                    note='[DEMO] Seeded booking'
                )
                if data['status'] in ['confirmed', 'completed']:
                    Payment.objects.create(
                        booking=booking,
                        amount=subtotal,
                        method='demo',
                        status='success',
                        provider_reference=f'DEMO-SEED-{booking.reference_number}',
                        paid_at=timezone.now(),
                    )
                    Payout.objects.create(
                        booking=booking,
                        institution=facility.institution,
                        amount=payout,
                        status='pending',
                    )
                count += 1
        self.stdout.write(f'  -- {count} demo bookings created')
